"""Mathematical utility functions and classes.

This module provides basic arithmetic operations implemented
using simple classes and functions.
"""

class MathOps:
    """Perform basic mathematical operations."""

    def add(self, a, b):
        """Add two numbers and return the result.

        Args:
            a: First number.
            b: Second number.

        Returns:
            The sum of a and b.
        """
        result = a + b
        return result


def square(x):
    """Return the square of a number.

    Args:
        x: Input number.

    Returns:
        The square of x.
    """
    y = x * x
    return y
